const thing = (
  id: string,
  title: string,
  tier: number,
  kind: ThingKind,
  stored: string[],
  partOf: string | undefined,
  summary: string,
  missing = false,
): Thing => ({
  id,
  title,
  tier,
  kind,
  stored,
  summary,
  ...(partOf ? { partOf } : {}),
  ...(missing ? { missing } : {}),
});

