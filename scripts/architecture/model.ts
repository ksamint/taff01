// Joins the code inventory with the module mapping and renders the generated
// part of the LikeC4 model. Pure functions; `generate.mts` writes the file.
import type {
  CoreFile,
  Inventory,
  Page,
  Route,
  Table,
  Tool,
} from "./inventory.ts";
import { MODULES, type ModuleMap } from "./modules.ts";

export type Assigned = {
  module: ModuleMap;
  tables: Table[];
  core: CoreFile[];
  routes: Route[];
  tools: Tool[];
  pages: Page[];
};
export type Assignment = {
  modules: Assigned[];
  /** Things in the code that no module claims. */
  unmapped: string[];
  /** Things claimed twice, or claimed but absent from the code. */
  conflicts: string[];
};

const first = (
  value: string,
  pick: (module: ModuleMap) => RegExp[],
): ModuleMap | undefined =>
  MODULES.find((module) => pick(module).some((rule) => rule.test(value)));

export function assign(inventory: Inventory): Assignment {
  const unmapped: string[] = [];
  const conflicts: string[] = [];
  const modules = MODULES.map((module) => ({
    module,
    tables: [] as Table[],
    core: [] as CoreFile[],
    routes: [] as Route[],
    tools: [] as Tool[],
    pages: [] as Page[],
  }));
  const of = (module: ModuleMap) =>
    modules.find((entry) => entry.module === module)!;
  // Tables and core files are claimed by exact name, once.
  const exact = <T extends { name: string }>(
    kind: string,
    items: T[],
    claims: (module: ModuleMap) => string[],
    put: (entry: Assigned, item: T) => void,
  ) => {
    for (const item of items) {
      const owners = MODULES.filter((m) => claims(m).includes(item.name));
      if (owners.length === 0) unmapped.push(`${kind} ${item.name}`);
      if (owners.length > 1)
        conflicts.push(
          `${kind} ${item.name} claimed by ${owners.map((m) => m.id).join(", ")}`,
        );
      if (owners[0]) put(of(owners[0]), item);
    }
    const names = new Set(items.map((item) => item.name));
    for (const module of MODULES)
      for (const name of claims(module))
        if (!names.has(name))
          conflicts.push(`${module.id} claims missing ${kind} ${name}`);
  };
  exact(
    "table",
    inventory.tables,
    (m) => m.tables,
    (e, t) => e.tables.push(t),
  );
  exact(
    "core file",
    inventory.core,
    (m) => m.core,
    (e, f) => e.core.push(f),
  );
  for (const route of inventory.routes) {
    const owner = first(route.path, (m) => m.routes);
    if (owner) of(owner).routes.push(route);
    else unmapped.push(`route ${route.method} ${route.path}`);
  }
  for (const tool of inventory.tools) {
    const owner = first(tool.name, (m) => m.tools);
    if (owner) of(owner).tools.push(tool);
    else unmapped.push(`tool ${tool.name}`);
  }
  for (const page of inventory.pages) {
    const owner = first(page.route, (m) => m.pages);
    if (owner) of(owner).pages.push(page);
    else unmapped.push(`page ${page.route}`);
  }
  return { modules, unmapped, conflicts };
}

const id = (value: string) =>
  value
    .replace(/^\//, "")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .replace(/^(\d)/, "_$1") || "root";
const text = (value: string) =>
  `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
/** Paths in the generated file are relative to architecture/generated/. */
const link = (file: string) => `link ../../${file}`;
const family = (route: string) =>
  route.startsWith("/api/")
    ? route.split("/").slice(0, 3).join("/")
    : route.split("/").slice(0, 2).join("/");

export function render(assignment: Assignment): string {
  const out: string[] = [
    "// GENERATED by scripts/architecture/generate.mts from the code and",
    "// scripts/architecture/modules.ts. Do not edit; run `pnpm arch:gen`.",
    "",
    "model {",
    "  extend fn {",
  ];
  const tablePath = new Map<string, string>();
  for (const entry of assignment.modules)
    for (const table of entry.tables)
      tablePath.set(table.name, `fn.${entry.module.id}.data.${id(table.name)}`);
  const uses: string[] = [];
  for (const {
    module,
    tables,
    core,
    routes,
    tools,
    pages,
  } of assignment.modules) {
    const lines: string[] = [];
    const layer = (key: string, title: string, tag: string, body: string[]) => {
      if (body.length === 0) return false;
      lines.push(
        `      ${key} = layer ${text(title)} {`,
        `        #${tag}`,
        ...body,
        "      }",
      );
      return true;
    };
    const screens = [
      ...pages.map(
        (page) =>
          `        ${id(`page_${page.route}`)} = screen ${text(page.route)} {\n          ${link(page.file)}\n        }`,
      ),
      ...(module.components ?? []).map(
        (name) =>
          `        ${id(name.replace(/\.tsx$/, ""))} = screen ${text(name)} {\n          ${link(`apps/web/src/components/${name}`)}\n        }`,
      ),
    ];
    const hasUi = layer("ui", "Screens", "web", screens);
    const families = new Map<string, Route[]>();
    for (const route of routes)
      families.set(family(route.path), [
        ...(families.get(family(route.path)) ?? []),
        route,
      ]);
    const hasRest = layer(
      "rest",
      "REST routes",
      "api",
      [...families].map(
        ([prefix, list]) =>
          `        ${id(prefix)} = routes ${text(`${prefix} (${list.length})`)} {\n          description ${text(list.map((r) => `${r.method} ${r.path}`).join("\n"))}\n          ${link(list[0]!.file)}\n        }`,
      ),
    );
    const hasMcp = layer(
      "mcp",
      "MCP tools",
      "mcp",
      tools.map(
        (tool) =>
          `        ${id(tool.name)} = tool ${text(tool.name)} {\n          description ${text(tool.title)}\n          ${link(tool.file)}\n        }`,
      ),
    );
    const others = (module.sources ?? []).map(
      (file) =>
        `        ${id(file.split("/").slice(-2).join("_"))} = code ${text(file.split("/").slice(-1)[0]!)} {\n          description ${text(file)}\n          ${link(file)}\n        }`,
    );
    const hasRules = layer("rules", "Rules and code", "core", [
      ...core.map(
        (file) =>
          `        ${id(file.name)} = code ${text(file.name)} {\n          ${link(file.file)}\n        }`,
      ),
      ...others,
    ]);
    layer(
      "data",
      "Tables",
      "db",
      tables.map(
        (table) => `        ${id(table.name)} = table ${text(table.name)}`,
      ),
    );
    if (hasUi && hasRest) lines.push("      ui -> rest 'calls'");
    if (hasRest && hasRules) lines.push("      rest -> rules 'calls'");
    if (hasMcp && hasRules) lines.push("      mcp -> rules 'calls'");
    out.push(
      `    ${module.id} = module ${text(module.title)} {`,
      `      description ${text(module.summary)}`,
      ...lines,
      "    }",
    );
    for (const file of core)
      for (const table of file.tables)
        uses.push(
          `  fn.${module.id}.rules.${id(file.name)} -[uses]-> ${tablePath.get(table)}`,
        );
  }
  out.push(
    "  }",
    "",
    "  // Which core file imports which table (from its @taff/db import).",
    ...uses.sort(),
    "}",
    "",
    "views {",
  );
  for (const { module } of assignment.modules)
    out.push(
      `  view ${module.id} of fn.${module.id} {`,
      `    title ${text(`Module · ${module.title}`)}`,
      `    include *, fn.${module.id}.**`,
      `    include fn.${module.id}.rules.* -> fn.**`,
      "  }",
    );
  out.push("}", "");
  return out.join("\n");
}
